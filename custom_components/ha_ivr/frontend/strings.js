export const langOf = (hass) => (String(hass?.locale?.language || hass?.language || "he").startsWith("he") ? "he" : "en");

export const isRTL = (hass) => Boolean(hass?.translationMetadata?.translations?.[hass?.language]?.isRTL ?? langOf(hass) === "he");

/**
 * פונקציית תרגום לשפה, עם {משתנים}. מפתח חסר נופל לעברית. כש-n הוא 1
 * ויש צורת יחיד (`<מפתח>_one`), היא נבחרת: "מכשיר אחד" ולא "1 מכשירים".
 */
export const translator = (lang) => (key, vars = {}) => {
  const pick = (k) => STRINGS[lang]?.[k] ?? STRINGS.he[k];
  const text = (vars.n === 1 && pick(`${key}_one`)) || pick(key) || key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
};
