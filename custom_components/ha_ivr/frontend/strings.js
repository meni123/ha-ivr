/** "he" לממשק בעברית, ואחרת "en". */
export const langOf = (hass) => (String((hass && (hass.locale?.language || hass.language)) || "he").startsWith("he") ? "he" : "en");

/** כיוון הכתיבה של הממשק, לפי מה ש-Home Assistant מדווח על השפה. */
export const isRTL = (hass) => {
  const language = String((hass && (hass.locale?.language || hass.language)) || "he");
  const meta = hass && hass.translationMetadata && hass.translationMetadata.translations;
  const found = meta && meta[language];
  if (found && typeof found.isRTL === "boolean") return found.isRTL;
  return /^(he|ar|fa|ur)\b/.test(language);
};

/** פונקציית תרגום לשפה אחת. מפתח חסר נופל לעברית, ואז למפתח עצמו. */
export const translator = (lang) => {
  const table = STRINGS[lang] || STRINGS.he;
  return (key, vars = {}) => {
    const raw = table[key] ?? STRINGS.he[key] ?? key;
    return raw.replace(/\{(\w+)\}/g, (all, name) => (name in vars ? String(vars[name]) : all));
  };
};

/** מספר עם צורת יחיד: "מקש אחד" / "3 מקשים". */
export const counted = (t, n, one, many) => (Number(n) === 1 ? t(one) : t(many, { n }));
